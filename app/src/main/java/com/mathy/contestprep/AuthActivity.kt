package com.mathy.contestprep

import android.app.Activity
import android.content.Intent
import android.os.Build
import android.os.Bundle
import android.view.View
import android.view.WindowManager
import android.widget.Button
import android.widget.EditText
import android.widget.Toast
import androidx.activity.enableEdgeToEdge
import androidx.activity.result.contract.ActivityResultContracts
import androidx.appcompat.app.AppCompatActivity
import androidx.cardview.widget.CardView
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat
import com.google.android.gms.auth.api.signin.GoogleSignIn
import com.google.android.gms.auth.api.signin.GoogleSignInClient
import com.google.android.gms.auth.api.signin.GoogleSignInOptions
import com.google.android.gms.common.api.ApiException
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import com.mathy.contestprep.DBhandler

class AuthActivity : AppCompatActivity() {

    private lateinit var auth: FirebaseAuth
    private lateinit var googleSignInClient: GoogleSignInClient
    // Add DB handler
    private lateinit var db: DBhandler

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        this.enableEdgeToEdge()
        setContentView(R.layout.activity_auth)

        // Maintaining your status bar theme from MainActivity
        if (Build.VERSION.SDK_INT >= 21) {
            val window = this.window
            window.addFlags(WindowManager.LayoutParams.FLAG_DRAWS_SYSTEM_BAR_BACKGROUNDS)
            window.clearFlags(WindowManager.LayoutParams.FLAG_TRANSLUCENT_STATUS)
            window.statusBarColor = this.resources.getColor(R.color.action, theme)
        }

        // Apply edge-to-edge padding (Assumes you add android:id="@+id/main_auth" to root)
        val mainView = findViewById<View>(android.R.id.content) // Generic fallback if ID isn't set
        ViewCompat.setOnApplyWindowInsetsListener(mainView) { v, insets ->
            val systemBars = insets.getInsets(WindowInsetsCompat.Type.systemBars())
            v.setPadding(systemBars.left, systemBars.top, systemBars.right, systemBars.bottom)
            insets
        }

        auth = FirebaseAuth.getInstance()

        // Configure Google Sign-In with the ID generated by Firebase
        val gso = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
            .requestIdToken(getString(R.string.default_web_client_id))
            .requestEmail()
            .build()

        googleSignInClient = GoogleSignIn.getClient(this, gso)

        auth = FirebaseAuth.getInstance()
        db = DBhandler(this) // Initialize your Power File

        // Mapping your layout IDs
        val btnGoogle = findViewById<CardView>(R.id.btnGoogle)
        val btnLogin = findViewById<Button>(R.id.btnLogin)
        val etEmail = findViewById<EditText>(R.id.etEmail)
        val etPassword = findViewById<EditText>(R.id.etPassword)

        // Google Sign-In Logic
        btnGoogle.setOnClickListener {
            val signInIntent = googleSignInClient.signInIntent
            googleLauncher.launch(signInIntent)
        }

        // Email/Password Login (Standard Logic)
        btnLogin.setOnClickListener {
            val email = etEmail.text.toString().trim()
            val pass = etPassword.text.toString().trim()

            if (email.isNotEmpty() && pass.isNotEmpty()) {
                auth.signInWithEmailAndPassword(email, pass).addOnCompleteListener { task ->
                    if (task.isSuccessful) {
                        handlePostLoginLogic() // Success: Return to MainActivity
                    } else {
                        // If user doesn't exist, try creating them (Sign-Up flow)
                        auth.createUserWithEmailAndPassword(email, pass).addOnCompleteListener { registerTask ->
                            if (registerTask.isSuccessful) {
                                handlePostLoginLogic()
                            } else {
                                Toast.makeText(this, "Error: ${registerTask.exception?.message}", Toast.LENGTH_LONG).show()
                            }
                        }
                    }
                }
            } else {
                Toast.makeText(this, "Please fill all fields", Toast.LENGTH_SHORT).show()
            }
        }
    }

    private val googleLauncher = registerForActivityResult(ActivityResultContracts.StartActivityForResult()) { result ->
        if (result.resultCode == Activity.RESULT_OK) {
            val task = GoogleSignIn.getSignedInAccountFromIntent(result.data)
            try {
                val account = task.getResult(ApiException::class.java)!!
                firebaseAuthWithGoogle(account.idToken!!)
            } catch (e: ApiException) {
                Toast.makeText(this, "Google Error: ${e.statusCode}", Toast.LENGTH_SHORT).show()
            }
        }
    }

    private fun firebaseAuthWithGoogle(idToken: String) {
        val credential = GoogleAuthProvider.getCredential(idToken, null)
        auth.signInWithCredential(credential).addOnCompleteListener(this) { task ->
            if (task.isSuccessful) {
                handlePostLoginLogic() // Call our new logic
            } else {
                Toast.makeText(this, "Firebase Connection Failed", Toast.LENGTH_SHORT).show()
            }
        }
    }

    private fun handlePostLoginLogic() {
        val user = auth.currentUser
        if (user != null) {
            // THE LONG GAME: Check if user already exists in Local DB
            val existingProfile = db.getUserProfile(user.uid)

            if (existingProfile == null) {
                // First time: Initialize with Google/Email name & default Avatar 1
                val initialName = user.displayName ?: "Math Titan"
                val initialAvatar = 1

                db.saveUserProfile(user.uid, initialName, user.email ?: "", initialAvatar)

                // OPTIONAL: You could also sync to Firestore here if you want it
                // in the cloud immediately, but Local-First is fine.
            }

            // SUCCESS: Redirect to Account Dashboard
            val intent = Intent(this, AccountActivity::class.java)
            startActivity(intent)
            finish() // Close AuthActivity so they can't "Back" into it
        }

        user?.sendEmailVerification()?.addOnCompleteListener { task ->
            if (task.isSuccessful) {
                Toast.makeText(this, "Verification email sent to ${user.email}", Toast.LENGTH_LONG).show()
            }
        }
    }
}